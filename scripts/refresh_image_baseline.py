"""Generate a reviewed, expiring Trivy ignore baseline for the container image.

The generated ``.trivyignore.yaml`` is the auditable record required by Rule 7
of ``AGENTS.md``. Only CRITICAL/HIGH findings are considered. Fixable findings
are rejected by default: a package with an available upgrade must be patched
rather than baselined.

Usage:
    python scripts/refresh_image_baseline.py scan.json --expires 2027-02-07
"""

from __future__ import annotations

import argparse
import json
import sys
from datetime import date
from pathlib import Path

CORE_PACKAGES = frozenset(
    {
        "chromium",
        "chromium-common",
        "curl",
        "libc6",
        "libc-bin",
        "libcrypto3",
        "libcurl3t64-gnutls",
        "libcurl4t64",
        "libexpat1",
        "libpython3.12",
        "libsqlite3-0",
        "libssl3t64",
        "libxml2",
        "node",
        "python3",
        "python3.12",
        "zlib1g",
    }
)

CORE_STATEMENT = (
    "Core runtime/render package: reachability and exploitability reviewed in "
    "docs/IMAGE_SECURITY_BASELINE.md."
)
PERIPHERAL_STATEMENT = (
    "Not loaded or executed on the default CLI or Mermaid render path; "
    "reachability analysis in docs/IMAGE_SECURITY_BASELINE.md."
)


def _load_findings(path: Path) -> dict[str, dict[str, object]]:
    payload = json.loads(path.read_text(encoding="utf-8"))
    findings: dict[str, dict[str, object]] = {}
    for result in payload.get("Results", []):
        for item in result.get("Vulnerabilities") or []:
            severity = str(item.get("Severity", "")).upper()
            if severity not in {"CRITICAL", "HIGH"}:
                continue
            cve = str(item.get("VulnerabilityID", "")).strip()
            if not cve:
                continue
            package = str(item.get("PkgName", "")).strip()
            entry = findings.setdefault(
                cve,
                {
                    "severity": severity,
                    "packages": set(),
                    "fixed_version": "",
                    "status": set(),
                },
            )
            packages = entry["packages"]
            statuses = entry["status"]
            assert isinstance(packages, set) and isinstance(statuses, set)
            packages.add(package)
            statuses.add(str(item.get("Status", "")).strip())
            if item.get("FixedVersion"):
                entry["fixed_version"] = str(item["FixedVersion"])
            if severity == "CRITICAL":
                entry["severity"] = "CRITICAL"
    return findings


def _classify(entry: dict[str, object]) -> tuple[bool, str]:
    packages = entry["packages"]
    assert isinstance(packages, set)
    core = bool(packages & CORE_PACKAGES)
    statement = CORE_STATEMENT if core else PERIPHERAL_STATEMENT
    return core, statement


def render(findings: dict[str, dict[str, object]], artifact: str, expires: date) -> str:
    lines = [
        "# Generated by scripts/refresh_image_baseline.py. Do not edit by hand.",
        f"# Artifact: {artifact}",
        f"# Expires: {expires.isoformat()} (re-review required after this date)",
        "#",
        "# Rule 7 baseline: each entry is CRITICAL/HIGH, has no fixed package",
        "# version, and has a documented reachability rationale. Expired entries",
        "# stop being ignored, so the image gate blocks until they are re-reviewed.",
        "vulnerabilities:",
    ]
    for cve in sorted(findings):
        entry = findings[cve]
        packages = entry["packages"]
        assert isinstance(packages, set)
        _, statement = _classify(entry)
        lines.append(f"  - id: {cve}")
        lines.append(f'    statement: "{statement}"')
        lines.append(f"    expired_at: {expires.isoformat()}")
    lines.append("")
    return "\n".join(lines)


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("report", type=Path, help="Trivy JSON report for the image")
    parser.add_argument(
        "--expires",
        type=date.fromisoformat,
        required=True,
        help="Expiry date for every baseline entry (YYYY-MM-DD)",
    )
    parser.add_argument(
        "--output",
        type=Path,
        default=Path(".trivyignore.yaml"),
        help="Output ignore file (default: .trivyignore.yaml)",
    )
    parser.add_argument(
        "--allow-fixable",
        action="store_true",
        help="Permit baselining findings that have a fixed package version",
    )
    args = parser.parse_args(argv)

    findings = _load_findings(args.report)
    fixable = sorted(cve for cve, entry in findings.items() if entry["fixed_version"])
    if fixable and not args.allow_fixable:
        print(
            "Refusing to baseline fixable findings (patch them instead): "
            + ", ".join(fixable),
            file=sys.stderr,
        )
        return 1

    artifact = args.report.name
    args.output.write_text(
        render(findings, artifact, args.expires), encoding="utf-8", newline="\n"
    )
    print(f"Wrote {args.output} with {len(findings)} baseline entries")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
